import random

def print_board(board):
    print('  1   2   3')
    print(f'1 {board[0][0]} | {board[0][1]} | {board[0][2]}')
    print('  ---+---+---')
    print(f'2 {board[1][0]} | {board[1][1]} | {board[1][2]}')
    print('  ---+---+---')
    print(f'3 {board[2][0]} | {board[2][1]} | {board[2][2]}')

def check_win(board, player):
    for row in board:
        if all(s == player for s in row):
            return True
    for col in range(3):
        if all(board[row][col] == player for row in range(3)):
            return True
    if all(board[i][i] == player for i in range(3)) or \
       all(board[i][2 - i] == player for i in range(3)):
        return True
    return False

def check_draw(board):
    for row in board:
        for spot in row:
            if spot == ' ':
                return False
    return True

def place_marker(board, player, row, col):
    if 0 <= row < 3 and 0 <= col < 3 and board[row][col] == ' ':
        board[row][col] = player
        return True
    return False

def get_player_choice(player):
    while True:
        try:
            row = int(input(f"Player {player}, enter row (1-3): ")) - 1
            col = int(input(f"Player {player}, enter column (1-3): ")) - 1
            if 0 <= row < 3 and 0 <= col < 3:
                return row, col
            else:
                print("Invalid input. Row and column must be between 1 and 3.")
        except ValueError:
            print("Invalid input. Please enter a number.")

def get_computer_choice(board):
    empty_spots = []
    for r in range(3):
        for c in range(3):
            if board[r][c] == ' ':
                empty_spots.append((r, c))
    return random.choice(empty_spots)

def play_game():
    board = [[' ' for _ in range(3)] for _ in range(3)]
    human_player = 'X'
    computer_player = 'O'
    current_player = human_player
    game_over = False

    print("Welcome to Tic Tac Toe!")
    print(f"You are '{human_player}', the computer is '{computer_player}'.")

    while not game_over:
        print_board(board)

        if current_player == human_player:
            row, col = get_player_choice(current_player)
        else:
            print(f"Computer ({computer_player}) is making a move...")
            row, col = get_computer_choice(board)

        if place_marker(board, current_player, row, col):
            if check_win(board, current_player):
                print_board(board)
                if current_player == human_player:
                    print(f"Player {current_player} wins! Congratulations!")
                else:
                    print(f"Computer ({current_player}) wins! Better luck next time!")
                game_over = True
            elif check_draw(board):
                print_board(board)
                print("It's a draw!")
                game_over = True
            else:
                current_player = computer_player if current_player == human_player else human_player
        else:
            if current_player == human_player:
                print("That spot is already taken or invalid. Try again.")

    print("Game Over!")

