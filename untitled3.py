import random
DIRTY = 0
CLEAN = 1
class Environment:
    def __init__(self, initial_state_A, initial_state_B):
        self.room_A = initial_state_A
        self.room_B = initial_state_B
        print("Initial Environment State:")
        self.display_state()

    def display_state(self):
        state_A = "Clean" if self.room_A == CLEAN else "Dirty"
        state_B = "Clean" if self.room_B == CLEAN else "Dirty"
        print(f"  Room A: {state_A} ({self.room_A})")
        print(f"  Room B: {state_B} ({self.room_B})")

    def get_room_state(self, room):
        if room == 'A':
            return self.room_A
        elif room == 'B':
            return self.room_B
        else:
            raise ValueError("Invalid room. Must be 'A' or 'B'.")

    def clean_room(self, room):
        if room == 'A':
            self.room_A = CLEAN
            print(f"    Room A cleaned.")
        elif room == 'B':
            self.room_B = CLEAN
            print(f"    Room B cleaned.")
        else:
            raise ValueError("Invalid room. Must be 'A' or 'B'.")

    def all_clean(self):
        return self.room_A == CLEAN and self.room_B == CLEAN

class VacuumCleanerAgent:
    def __init__(self, environment, initial_location):
        self.environment = environment
        self.location = initial_location
        print(f"Vacuum Cleaner starts in Room {self.location}.")

    def perceive(self):
        room_state = self.environment.get_room_state(self.location)
        return self.location, room_state

    def act(self, room_location, room_state):
        print(f"  Agent is in Room {room_location}. It perceives the room as {"Clean" if room_state == CLEAN else "Dirty"}.")
        if room_state == DIRTY:
            print(f"    Cleaning Room {room_location}...")
            self.environment.clean_room(room_location)
            return 'Clean'
        else:
            if room_location == 'A':
                self.location = 'B'
                print("    Room A is clean, moving to Room B.")
                return 'Move B'
            else:
                self.location = 'A'
                print("    Room B is clean, moving to Room A.")
                return 'Move A'

def run_simulation(steps=10):
    while True:
        state_A_input = input("Enter initial state for Room A (0 for DIRTY, 1 for CLEAN): ")
        try:
            initial_state_A = int(state_A_input)
            if initial_state_A in [DIRTY, CLEAN]:
                break
            else:
                print("Invalid input. Please enter 0 or 1.")
        except ValueError:
            print("Invalid input. Please enter a number (0 or 1).")
    while True:
        state_B_input = input("Enter initial state for Room B (0 for DIRTY, 1 for CLEAN): ")
        try:
            initial_state_B = int(state_B_input)
            if initial_state_B in [DIRTY, CLEAN]:
                break
            else:
                print("Invalid input. Please enter 0 or 1.")
        except ValueError:
            print("Invalid input. Please enter a number (0 or 1).")

    env = Environment(initial_state_A, initial_state_B)

    while True:
        user_location = input("Enter the vacuum cleaner's starting room (A or B): ").upper()
        if user_location in ['A', 'B']:
            break
        else:
            print("Invalid input. Please enter 'A' or 'B'.")

    agent = VacuumCleanerAgent(env, user_location)

    for step in range(steps):
        print(f"\n--- Step {step + 1} ---")
        if env.all_clean():
            print("All rooms are clean! Simulation ended.")
            break

        current_location, current_room_state = agent.perceive()
        agent.act(current_location, current_room_state)

    if not env.all_clean():
        print("\nSimulation finished because max steps reached. Not all rooms are clean.")
    else:
        print("\nSimulation finished. All rooms are clean.")
    env.display_state()

"""To run the simulation, execute the cell below. You can change the `steps` parameter to control how long the simulation runs if the rooms don't get clean quickly."""

run_simulation(steps=20)